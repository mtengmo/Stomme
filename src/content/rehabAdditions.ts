import type { Exercise, ExerciseId, Load } from '../domain/types';

const bodyweight: Load = { kg: 0, label: 'Kroppsvikt' };

function addition(
  id: ExerciseId,
  name: string,
  muscles: string[],
  tips: Exercise['tips'],
  commonMistake: string,
  easierVariant: string,
  unit: Exercise['unit'],
  range: Exercise['range'],
  perSide = false,
  sideKind: Exercise['sideKind'] = 'ben',
  kneeLoaded = false,
): Exercise {
  return {
    id,
    name,
    muscles,
    tips,
    commonMistake,
    easierVariant,
    unit,
    perSide,
    ...(perSide ? { sideKind } : {}),
    range,
    loadLadder: [bodyweight],
    startLoadIndex: 0,
    week1LoadIndex: 0,
    kneeLoaded,
    optional: true,
  };
}

