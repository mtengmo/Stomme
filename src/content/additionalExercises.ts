/** Library defaults are editable starting points, not an AAOS prescription. */
function entry(
  id: ExerciseId,
  name: string,
  muscles: string[],
  tips: Exercise['tips'],
  commonMistake: string,
  easierVariant: string,
  loads: Load[],
  perSide = false,
  unit: Exercise['unit'] = 'reps',
): Exercise {
  return {
    id,
    name,
    muscles,
    tips,
    commonMistake,
    easierVariant,
    unit,
    perSide,
    ...(perSide
      ? {
          sideKind:
            id === 'kettlebell-rack-carry'
              ? ('hand' as const)
              : [
                    'supported-row',
                    'triceps-kickback',
                    'kettlebell-press',
                    'single-arm-thruster',
                    'kettlebell-floor-press',
                    'kettlebell-rack-carry',
                  ].includes(id)
                ? ('sida' as const)
                : ('ben' as const),
        }
      : {}),
    range:
      unit === 'seconds'
        ? { start: 20, max: 30, step: 5 }
        : unit === 'meters'
          ? { start: 10, max: 20, step: 5 }
          : unit === 'laps'
            ? { start: 3, max: 6, step: 1 }
            : { start: 8, max: 12, step: 1 },
    loadLadder: loads,
    startLoadIndex: 0,
    week1LoadIndex: 0,
    kneeLoaded: kneeLoadedAdditional.has(id),
  };
}

