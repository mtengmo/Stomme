import type { Exercise, ExerciseId, Load } from '../domain/types';

const bw: Load = { kg: 0, label: 'Kroppsvikt' };
const single = (kg: number, tool = 'hantel'): Load => ({
  kg,
  label: `1 × ${kg} kg ${tool} · totalt ${kg} kg`,
});
const pair = (kg: number, tool = 'hantlar'): Load => ({
  kg: kg * 2,
  label: `2 × ${kg} kg ${tool} · totalt ${kg * 2} kg`,
});

/** Library defaults are editable starting points, not an AAOS prescription. */
function entry(
  id: ExerciseId,
  name: string,
  muscles: string[],
  tips: Exercise['tips'],
  commonMistake: string,
  easierVariant: string,
  loads: Load[],
  perSide = false,
  unit: Exercise['unit'] = 'reps',
): Exercise {
  return {
    id,
    name,
    muscles,
    tips,
    commonMistake,
    easierVariant,
    unit,
    perSide,
    ...(perSide
      ? {
          sideKind: [
            'supported-row',
            'triceps-kickback',
            'kettlebell-press',
          ].includes(id)
            ? ('sida' as const)
            : ('ben' as const),
        }
      : {}),
    range:
      unit === 'seconds'
        ? { start: 20, max: 30, step: 5 }
        : unit === 'meters'
          ? { start: 10, max: 20, step: 5 }
          : { start: 8, max: 12, step: 1 },
    loadLadder: loads,
    startLoadIndex: 0,
    week1LoadIndex: 0,
    kneeLoaded: false,
  };
}

